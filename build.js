// Builds the website (docs/) and the server function (supabase/functions/race-api/) from src/.
// Run: node build.js
const fs = require('fs'), path = require('path');
const R = (...p) => path.join(__dirname, ...p);
const read = f => fs.readFileSync(R('src', f), 'utf8');
const write = (f, s) => { fs.mkdirSync(path.dirname(R(f)), { recursive: true }); fs.writeFileSync(R(f), s); };

// website, served by GitHub Pages from the docs/ folder
write('docs/index.html', `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="theme-color" content="#0E2A47">
<title>RWO Registration</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Barlow+Condensed:wght@500;600;700;800&family=Barlow:wght@400;500;600;700&display=swap" rel="stylesheet">
<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns=%22http://www.w3.org/2000/svg%22 viewBox=%220 0 32 32%22%3E%3Crect width=%2232%22 height=%2232%22 rx=%226%22 fill=%22%230E2A47%22/%3E%3Cpath d=%22M8 17l5 5 11-12%22 stroke=%22%23FFC400%22 stroke-width=%224%22 fill=%22none%22/%3E%3C/svg%3E">
<link rel="stylesheet" href="styles.css">
<script src="config.js"></script>
</head>
<body>
<noscript>RWO Registration needs JavaScript turned on.</noscript>
<script>
(function () {
  var c = window.RWO_CONFIG || {};
  var demo = !c.url || /[?&]demo=1/.test(location.search);
  var list = demo ? ['logic.js', 'memorystore.js', 'demo.js', 'app.js']
                  : ['https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2/dist/umd/supabase.min.js', 'app.js'];
  (function next(i) {
    if (i >= list.length) return;
    var s = document.createElement('script');
    s.src = list[i];
    s.onload = s.onerror = function () { next(i + 1); };
    document.body.appendChild(s);
  })(0);
})();
</script>
</body>
</html>
`);
write('docs/styles.css', read('styles.css'));
write('docs/app.js', read('app.js'));
write('docs/logic.js', read('logic.js'));
write('docs/memorystore.js', read('MemoryStore.js'));
write('docs/demo.js', read('demo.js'));
if (!fs.existsSync(R('docs/config.js'))) write('docs/config.js', `// RWO Registration settings for this website.
// Leave url empty to run the demo with made-up data.
// After setup (guide step 5), paste your Supabase Project URL and Publishable key here.
window.RWO_CONFIG = {
  url: '',          // e.g. 'https://abcdefghijklmnop.supabase.co'
  key: '',          // the Publishable key (starts with sb_publishable_). Safe to be public.
  fn: 'race-api'    // name of the server function
};
`);
write('docs/.nojekyll', '');

// server function: one self-contained file, so it can also be pasted into the Supabase dashboard editor
write('supabase/functions/race-api/index.ts', `// @ts-nocheck
// RWO Registration server function. GENERATED by build.js from src/ (logic.js, MemoryStore.js, adapter.js).
// Edit those files and run "node build.js", or paste this whole file into Supabase > Edge Functions > race-api.
import { createClient } from 'npm:@supabase/supabase-js@2';

${read('logic.js')}

${read('MemoryStore.js')}

${read('adapter.js')}

Deno.serve(makeHandler(createClient, (k) => Deno.env.get(k)));
`);
write('supabase/config.toml', `# Used by the GitHub deploy action. The function checks department PINs itself,
# and browsers call it with the public "publishable" key, so the platform JWT check is off.
[functions.race-api]
verify_jwt = false
`);
console.log('Built docs/ and supabase/functions/race-api/index.ts');
